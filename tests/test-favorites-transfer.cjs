const assert = require('node:assert/strict');
const transfer = require('../public/assets/js/favorites-transfer.js');
const msgpack = require('../public/assets/js/vendor/msgpack.min.js');
const now = new Date('2026-11-15T12:34:56.789Z');
const bytes = transfer.encode(['n5-a','n1-b','n5-a'],now);
assert.deepEqual(msgpack.decode(bytes), {format:'japanword-favorites',version:1,exportedAt:now.toISOString(),favorites:['n5-a','n1-b']});
assert.deepEqual(transfer.decode(bytes).favorites,['n5-a','n1-b']);
assert.equal(transfer.filename(now),'japanword-favorites-2026-11-15T12-34-56-789Z.msgpack');
const known = new Set(['n5-a','n1-b','retired']);
assert.deepEqual(transfer.merge(['n5-a','preserved-unknown'],['old','n1-b','n1-b','missing'],known,{old:'n5-a'}),{favorites:['n5-a','preserved-unknown','n1-b'],added:1,skipped:1});
assert.deepEqual(transfer.merge(['n5-a'],[],known).favorites,['n5-a'],'Empty backup must not cancel current favorites');
assert.equal(transfer.merge(['n5-a','n1-b'],['n1-b'],known).added,0,'Repeated import must be idempotent');
for (const value of [null,{}, {...msgpack.decode(bytes),version:2}, {...msgpack.decode(bytes),exportedAt:'bad'}, {...msgpack.decode(bytes),favorites:[false]}, {...msgpack.decode(bytes),favorites:['a'.repeat(129)]}]) assert.throws(()=>transfer.decode(msgpack.encode(value)));
assert.throws(()=>transfer.decode(new Uint8Array()));
assert.throws(()=>transfer.decode(new Uint8Array(transfer.MAX_BYTES+1)));
assert.throws(()=>transfer.decode(bytes.slice(0,-1)));
assert.throws(()=>transfer.decode(Uint8Array.from([...bytes,0])));
assert.throws(()=>transfer.decode(Uint8Array.from([0xdd,0xff,0xff,0xff,0xff])));
console.log('PASS: interoperable MessagePack, UTC timestamps, OR merge, legacy IDs, duplicates, unknown IDs, invalid files and size bounds.');
